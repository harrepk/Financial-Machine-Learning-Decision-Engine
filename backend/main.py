"""FastAPI backend for the Financial Decision Engine.

Run from the project root:
    uvicorn backend.main:app --reload --port 8000

Interactive API docs (auto-generated by FastAPI): http://localhost:8000/docs
"""
from __future__ import annotations

import logging
from contextlib import asynccontextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Annotated

from fastapi import Depends, FastAPI, HTTPException, Query, Request

from backend import config
from backend.database import fetch_all_cards, init_db
from backend.matcher import CardMatcher
from backend.predictor import ApprovalPredictor, ModelNotTrainedError
from backend.schemas import (
    Applicant,
    ApprovalBand,
    Card,
    CardMatch,
    CardPrediction,
    HealthResponse,
    MatchResponse,
    PredictRequest,
    PredictResponse,
    Recommendation,
    RecommendRequest,
    RecommendResponse,
)

logger = logging.getLogger("uvicorn.error")

NO_MATCH_MESSAGE = (
    "No cards matched your search. Try words like 'travel', 'cash back', 'groceries', "
    "'student', 'no annual fee' or 'low interest'."
)


@dataclass
class Engine:
    """Everything loaded into memory at startup and shared by all requests."""

    cards: dict[int, Card]
    matcher: CardMatcher
    predictor: ApprovalPredictor | None


# ---------- Dependencies (FastAPI injects these into the route functions) ----------

def get_engine(request: Request) -> Engine:
    return request.app.state.engine


EngineDep = Annotated[Engine, Depends(get_engine)]


def require_predictor(engine: EngineDep) -> ApprovalPredictor:
    if engine.predictor is None:
        raise HTTPException(status_code=503, detail="Model not trained yet. Run:  python -m ml.train")
    return engine.predictor


PredictorDep = Annotated[ApprovalPredictor, Depends(require_predictor)]


# ---------- Helpers ----------

def approval_band(probability: float) -> ApprovalBand:
    if probability >= config.HIGH_APPROVAL:
        return "High"
    if probability >= config.MODERATE_APPROVAL:
        return "Moderate"
    return "Low"


def build_insights(applicant: Applicant, recommendations: list[Recommendation]) -> list[str]:
    """Plain-English tips that explain the numbers, so the result is not a black box."""
    insights = []
    dti = applicant.existing_debt / applicant.annual_income
    debt_share = f"Your debt is {dti:.0%} of your yearly income."
    if dti < 0.20:
        insights.append(f"{debt_share} Lenders generally see that as low and healthy.")
    elif dti < 0.40:
        insights.append(f"{debt_share} That is manageable; staying under 40% helps approvals.")
    else:
        insights.append(
            f"{debt_share} Paying it down below 40% is likely the biggest single way to improve your approval odds."
        )

    if applicant.credit_score < 600:
        insights.append(
            "A credit score under 600 limits options. Starter and secured cards are built for rebuilding credit."
        )
    elif applicant.credit_score < 700:
        insights.append(
            "A score in the 600s qualifies for many standard cards. "
            "Paying every bill on time is the fastest way past 700."
        )
    else:
        insights.append("A score of 700 or more is generally considered good to excellent by Canadian lenders.")

    below_guideline = [r.card.name for r in recommendations if not r.meets_income_guideline]
    if below_guideline:
        insights.append("Your income is below the issuer's suggested minimum for: " + ", ".join(below_guideline) + ".")
    return insights


# ---------- Application ----------

def create_app(
    db_path: Path = config.DB_PATH,
    seed_path: Path = config.CARDS_SEED_PATH,
    model_path: Path = config.MODEL_PATH,
) -> FastAPI:
    """Application factory. Tests call this with temporary paths; production uses the defaults."""

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        # Load the database, TF-IDF index and neural network ONCE at startup and keep them
        # in memory. Loading them inside each request would make every call slow.
        card_count = init_db(db_path, seed_path)
        cards = fetch_all_cards(db_path)
        try:
            predictor = ApprovalPredictor(model_path)
        except ModelNotTrainedError as exc:
            logger.warning("%s  (the /predict and /recommend endpoints will return 503 until then)", exc)
            predictor = None
        app.state.engine = Engine(cards={c.id: c for c in cards}, matcher=CardMatcher(cards), predictor=predictor)
        logger.info("Engine ready: %d cards, model loaded: %s", card_count, predictor is not None)
        yield

    app = FastAPI(
        title="Financial Decision Engine API",
        version="1.0.0",
        description=(
            "Stage 1 matches credit cards to a plain-English search with TF-IDF + cosine similarity. "
            "Stage 2 estimates approval odds for each match with a PyTorch neural network."
        ),
        lifespan=lifespan,
    )

    @app.get("/health", response_model=HealthResponse, tags=["system"])
    def health(engine: EngineDep) -> HealthResponse:
        return HealthResponse(
            status="ok",
            cards_loaded=len(engine.cards),
            predictor_loaded=engine.predictor is not None,
            predictor_metrics=engine.predictor.metrics if engine.predictor else None,
        )

    @app.get("/cards", response_model=list[Card], tags=["catalogue"])
    def list_cards(engine: EngineDep) -> list[Card]:
        return list(engine.cards.values())

    @app.get("/match", response_model=MatchResponse, tags=["stage 1: matchmaker"])
    def match(
        engine: EngineDep,
        query: Annotated[str, Query(min_length=2, max_length=200, examples=["no foreign transaction fee travel card"])],
        top_k: Annotated[int, Query(ge=1, le=5)] = config.DEFAULT_TOP_K,
    ) -> MatchResponse:
        """Stage 1 only: rank cards by how well they match a plain-English search."""
        matches = engine.matcher.search(query, top_k=top_k)
        return MatchResponse(
            query=query,
            matches=[CardMatch(card=m.card, match_score=round(m.score, 4)) for m in matches],
            message=f"Found {len(matches)} matching card(s)." if matches else NO_MATCH_MESSAGE,
        )

    @app.post("/predict", response_model=PredictResponse, tags=["stage 2: predictor"])
    def predict(request: PredictRequest, engine: EngineDep, predictor: PredictorDep) -> PredictResponse:
        """Stage 2 only: approval probability for specific card ids."""
        unknown = [card_id for card_id in request.card_ids if card_id not in engine.cards]
        if unknown:
            raise HTTPException(status_code=404, detail=f"Unknown card id(s): {unknown}")
        cards = [engine.cards[card_id] for card_id in request.card_ids]
        probabilities = predictor.predict(
            request.credit_score, request.annual_income, request.existing_debt, [c.tier for c in cards]
        )
        return PredictResponse(
            predictions=[
                CardPrediction(card_id=c.id, approval_probability=round(p, 4), approval_band=approval_band(p))
                for c, p in zip(cards, probabilities, strict=True)
            ]
        )

    @app.post("/recommend", response_model=RecommendResponse, tags=["full pipeline"])
    def recommend(request: RecommendRequest, engine: EngineDep, predictor: PredictorDep) -> RecommendResponse:
        """The full pipeline the UI uses: Stage 1 (find matching cards) then Stage 2 (score each one)."""
        applicant = Applicant(
            credit_score=request.credit_score,
            annual_income=request.annual_income,
            existing_debt=request.existing_debt,
        )
        matches = engine.matcher.search(request.query, top_k=request.top_k)
        probabilities = predictor.predict(
            applicant.credit_score, applicant.annual_income, applicant.existing_debt, [m.card.tier for m in matches]
        )
        recommendations = [
            Recommendation(
                card=m.card,
                match_score=round(m.score, 4),
                approval_probability=round(p, 4),
                approval_band=approval_band(p),
                meets_income_guideline=applicant.annual_income >= m.card.min_income,
            )
            for m, p in zip(matches, probabilities, strict=True)
        ]
        return RecommendResponse(
            query=request.query,
            applicant=applicant,
            debt_to_income=round(applicant.existing_debt / applicant.annual_income, 4),
            recommendations=recommendations,
            insights=build_insights(applicant, recommendations),
            message=f"Found {len(recommendations)} matching card(s)." if recommendations else NO_MATCH_MESSAGE,
        )

    return app


app = create_app()
